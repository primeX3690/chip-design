"""
testbench_generator.py
-----------------------
Generates a self-checking Verilator C++ testbench for the ALU interface.

Design choice: rather than trying to parse arbitrary mutated Verilog ports
(fragile), EvoHDL fixes the ALU's port contract (a, b, opcode -> result,
carry_out, zero_flag) for the whole run. Mutation/crossover operate on the
*implementation* inside the module, never on the interface. This keeps every
generated design instantiable by the same testbench, which is what makes an
apples-to-apples fitness comparison possible.

The golden reference model lives in Python (`golden_alu`) so we never need a
second Verilog "known-good" implementation to drift out of sync.
"""

from __future__ import annotations

import random
from pathlib import Path
from typing import List, Tuple

MODULE_NAME_PLACEHOLDER = "__MODULE_NAME__"

CPP_TEMPLATE = r"""
// AUTO-GENERATED by testbench_generator.py -- do not edit by hand.
#include <verilated.h>
#include "V__MODULE_NAME__.h"
#include <cstdio>
#include <cstdint>

struct Vector {
    uint8_t a;
    uint8_t b;
    uint8_t opcode;
    uint8_t expected_result;
    uint8_t expected_carry;
};

// {VECTORS}

int main(int argc, char** argv) {
    Verilated::commandArgs(argc, argv);
    V__MODULE_NAME__* dut = new V__MODULE_NAME__;

    int total = sizeof(vectors) / sizeof(Vector);
    int passed = 0;

    for (int i = 0; i < total; i++) {
        dut->a = vectors[i].a;
        dut->b = vectors[i].b;
        dut->opcode = vectors[i].opcode;
        dut->eval();

        bool result_ok = (dut->result == vectors[i].expected_result);
        bool carry_ok  = (dut->carry_out == vectors[i].expected_carry);

        if (result_ok && carry_ok) {
            passed++;
        } else {
            fprintf(stderr,
                "MISMATCH vec=%d a=%d b=%d op=%d got_r=%d exp_r=%d got_c=%d exp_c=%d\n",
                i, vectors[i].a, vectors[i].b, vectors[i].opcode,
                dut->result, vectors[i].expected_result,
                dut->carry_out, vectors[i].expected_carry);
        }
    }

    printf("EVOHDL_RESULT passed=%d total=%d\n", passed, total);

    delete dut;
    return (passed == total) ? 0 : 1;
}
"""


def golden_alu(a: int, b: int, opcode: int) -> Tuple[int, int]:
    """Reference (correct-by-definition) ALU behaviour. Returns (result, carry)."""
    a &= 0xFF
    b &= 0xFF
    if opcode == 0b000:  # ADD
        total = a + b
        return total & 0xFF, 1 if total > 0xFF else 0
    if opcode == 0b001:  # SUB
        total = a - b
        return total & 0xFF, 1 if total < 0 else 0
    if opcode == 0b010:  # AND
        return a & b, 0
    if opcode == 0b011:  # OR
        return a | b, 0
    if opcode == 0b100:  # XOR
        return a ^ b, 0
    if opcode == 0b101:  # NOT A
        return (~a) & 0xFF, 0
    if opcode == 0b110:  # SHL
        return (a << 1) & 0xFF, 0
    if opcode == 0b111:  # SHR
        return (a >> 1) & 0xFF, 0
    return 0, 0


def generate_vectors(num_random: int = 200, seed: int | None = None) -> List[Tuple[int, int, int, int, int]]:
    """
    Build directed corner-case vectors + random vectors.
    Returns list of (a, b, opcode, expected_result, expected_carry).
    """
    rng = random.Random(seed)
    vectors = []

    corner_values = [0x00, 0x01, 0x7F, 0x80, 0xFE, 0xFF]
    for opcode in range(8):
        for a in corner_values:
            for b in corner_values:
                r, c = golden_alu(a, b, opcode)
                vectors.append((a, b, opcode, r, c))

    for _ in range(num_random):
        a = rng.randint(0, 255)
        b = rng.randint(0, 255)
        opcode = rng.randint(0, 7)
        r, c = golden_alu(a, b, opcode)
        vectors.append((a, b, opcode, r, c))

    return vectors


def render_testbench(module_name: str, num_random_vectors: int = 200, seed: int | None = 42) -> str:
    vectors = generate_vectors(num_random_vectors, seed=seed)
    lines = ["static Vector vectors[] = {"]
    for (a, b, op, r, c) in vectors:
        lines.append(f"    {{{a}, {b}, {op}, {r}, {c}}},")
    lines.append("};")
    vector_block = "\n".join(lines)

    cpp = CPP_TEMPLATE.replace("// {VECTORS}", vector_block)
    cpp = cpp.replace(MODULE_NAME_PLACEHOLDER, module_name)
    return cpp


def write_testbench(module_name: str, out_path: str | Path, num_random_vectors: int = 200, seed: int | None = 42) -> Path:
    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(render_testbench(module_name, num_random_vectors, seed))
    return out_path


if __name__ == "__main__":
    p = write_testbench("alu_basic", "/tmp/evohdl_tb_demo.cpp")
    print(f"Wrote demo testbench to {p}")
