"""
testbench_generator.py
-----------------------
Generates a self-checking Verilator C++ testbench for a design under
evolution.

Design choice: rather than trying to parse arbitrary mutated Verilog ports
(fragile), EvoHDL fixes each supported module's port contract for the whole
run. Mutation/crossover operate on the *implementation* inside the module,
never on the interface. This keeps every generated design instantiable by
the same testbench, which is what makes an apples-to-apples fitness
comparison possible.

Every golden reference model lives in Python so we never need a second
Verilog "known-good" implementation to drift out of sync.

Multi-module support: `render_testbench(module_name, ...)` dispatches on
module_name to the matching renderer in MODULE_RENDERERS below. This is the
"extension point" the original alu_basic-only version of this file left
documented in designs/seed/comparator_4bit.v -- picorv32_alu.v is the first
design to actually use it, and it establishes the pattern for adding more
(e.g. wiring up comparator_4bit / counter_4bit the same way).
"""

from __future__ import annotations

import random
from pathlib import Path
from typing import Callable, List, Tuple

MODULE_NAME_PLACEHOLDER = "__MODULE_NAME__"

