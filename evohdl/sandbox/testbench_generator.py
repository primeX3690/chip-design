ALU_BASIC_CPP_TEMPLATE = r"""
// AUTO-GENERATED by testbench_generator.py -- do not edit by hand.
#include <verilated.h>
#include "V__MODULE_NAME__.h"
#include <cstdio>
#include <cstdint>

struct Vector {
    uint8_t a;
    uint8_t b;
    uint8_t opcode;
    uint8_t expected_result;
    uint8_t expected_carry;
    uint8_t expected_zero;
};

// {VECTORS}

int main(int argc, char** argv) {
    Verilated::commandArgs(argc, argv);
    V__MODULE_NAME__* dut = new V__MODULE_NAME__;

    int total = sizeof(vectors) / sizeof(Vector);
    int passed = 0;

    for (int i = 0; i < total; i++) {
        dut->a = vectors[i].a;
        dut->b = vectors[i].b;
        dut->opcode = vectors[i].opcode;
        dut->eval();

        bool result_ok = (dut->result == vectors[i].expected_result);
        bool carry_ok  = (dut->carry_out == vectors[i].expected_carry);
        // zero_flag MUST be checked: it used to be unobserved, and the GA "optimized" the ALU by deleting that logic.
        bool zero_ok   = (dut->zero_flag == vectors[i].expected_zero);

        if (result_ok && carry_ok && zero_ok) {
            passed++;
        } else {
            fprintf(stderr,
                "MISMATCH vec=%d a=%d b=%d op=%d got_r=%d exp_r=%d got_c=%d exp_c=%d got_z=%d exp_z=%d\n",
                i, vectors[i].a, vectors[i].b, vectors[i].opcode,
                dut->result, vectors[i].expected_result,
                dut->carry_out, vectors[i].expected_carry,
                dut->zero_flag, vectors[i].expected_zero);
        }
    }

    printf("EVOHDL_RESULT passed=%d total=%d\n", passed, total);

    delete dut;
    return (passed == total) ? 0 : 1;
}
"""


def golden_alu(a: int, b: int, opcode: int) -> Tuple[int, int]:
    """Reference (correct-by-definition) ALU behaviour. Returns (result, carry)."""
    a &= 0xFF
    b &= 0xFF
    if opcode == 0b000:  # ADD
        total = a + b
        return total & 0xFF, 1 if total > 0xFF else 0
    if opcode == 0b001:  # SUB
        total = a - b
        return total & 0xFF, 1 if total < 0 else 0
    if opcode == 0b010:  # AND
        return a & b, 0
    if opcode == 0b011:  # OR
        return a | b, 0
    if opcode == 0b100:  # XOR
        return a ^ b, 0
    if opcode == 0b101:  # NOT A
        return (~a) & 0xFF, 0
    if opcode == 0b110:  # SHL
        return (a << 1) & 0xFF, 0
    if opcode == 0b111:  # SHR
        return (a >> 1) & 0xFF, 0
    return 0, 0


def _generate_alu_basic_vectors(num_random: int = 200, seed: int | None = None) -> List[Tuple[int, int, int, int, int]]:
    """
    Build directed corner-case vectors + random vectors.
    Returns list of (a, b, opcode, expected_result, expected_carry).
    """
    rng = random.Random(seed)
    vectors = []

    corner_values = [0x00, 0x01, 0x7F, 0x80, 0xFE, 0xFF]
    for opcode in range(8):
        for a in corner_values:
            for b in corner_values:
                r, c = golden_alu(a, b, opcode)
                vectors.append((a, b, opcode, r, c))

    for _ in range(num_random):
        a = rng.randint(0, 255)
        b = rng.randint(0, 255)
        opcode = rng.randint(0, 7)
        r, c = golden_alu(a, b, opcode)
        vectors.append((a, b, opcode, r, c))

    return vectors


def _render_alu_basic_testbench(module_name: str, num_random_vectors: int = 200, seed: int | None = 42) -> str:
    vectors = _generate_alu_basic_vectors(num_random_vectors, seed=seed)
    lines = ["static Vector vectors[] = {"]
    for (a, b, op, r, c) in vectors:
        lines.append(f"    {{{a}, {b}, {op}, {r}, {c}, {1 if r == 0 else 0}}},")   # last field: expected zero_flag
    lines.append("};")
    vector_block = "\n".join(lines)

    cpp = ALU_BASIC_CPP_TEMPLATE.replace("// {VECTORS}", vector_block)
    cpp = cpp.replace(MODULE_NAME_PLACEHOLDER, module_name)
    return cpp


